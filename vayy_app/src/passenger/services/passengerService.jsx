/**
 * Fetch recent searches for the passenger.
 * The backend answers flat with asymmetric lng/lon names; the shared normalizer
 * maps it to the nested {pickup,destination} shape the screens read.
 */
export const getRecentSearches = async () => {
  try {
    const response = await api.get(AUTH.recentSearches);
    const data = response.data?.data ?? response.data;
    if (!Array.isArray(data)) return [];
    return data.map(normalizeRecentSearch).filter(Boolean);
  } catch (error) {
    console.error("Failed to fetch recent searches:", error);
    return [];
  }
};

